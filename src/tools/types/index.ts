import { z } from "zod";
import { ToolContext, ToolServer } from "../../context.js";
import { buildModel } from "../../typegen/model.js";
import { typescript } from "../../typegen/typescript.js";
import { swift } from "../../typegen/swift.js";
import { kotlin } from "../../typegen/kotlin.js";
import { dart } from "../../typegen/dart.js";

const GENERATORS = { typescript, swift, kotlin, dart };
const FENCE: Record<keyof typeof GENERATORS, string> = {
  typescript: "ts",
  swift: "swift",
  kotlin: "kotlin",
  dart: "dart",
};

export function registerTypeTools(server: ToolServer, ctx: ToolContext): void {
  server.tool(
    "generate_types",
    "Generate typed classes from an app's schema for its client code: TypeScript (Parse JS SDK), Swift (ParseSwift), Kotlin (Parse Android SDK) or Dart (parse_server_sdk). Pointers become the target class's type; the SDKs' own fields (objectId, createdAt, ...) are left to them.",
    {
      appObjectId: z.string().describe("The application object ID"),
      language: z.enum(["typescript", "swift", "kotlin", "dart"]).describe("The client's language and SDK"),
      classes: z
        .array(z.string())
        .optional()
        .describe("Only these classes (as named in Parse, e.g. _User, Post); default: all of the app's own and _User, _Role, _Installation"),
    },
    async (args) => {
      const [schemas, appName] = await Promise.all([
        ctx.parse(args.appObjectId).listClasses(),
        ctx.appName(args.appObjectId),
      ]);
      const models = buildModel(schemas, args.classes);
      if (!models.length) {
        return {
          content: [
            {
              type: "text" as const,
              text: `❌ No classes${args.classes ? ` named ${args.classes.join(", ")}` : ""} in ${appName}. Its classes: ${schemas.map((s) => s.className).join(", ")}.`,
            },
          ],
        };
      }
      const header = `Generated by the SashiDo MCP server from ${appName}'s schema (${models.length} classes), ${new Date().toISOString().slice(0, 10)}`;
      const code = GENERATORS[args.language](models, header);
      return {
        content: [{ type: "text" as const, text: `\`\`\`${FENCE[args.language]}\n${code}\`\`\`` }],
      };
    },
  );
}
